#!/usr/bin/env python3
"""Build components/holidays_data.h, the Norwegian public holidays shown in
red on the month calendar (main/month.c), from norskkalender.no.

Each year's page lists the month's holidays under the month as
"<b>1.1</b>: 1. nyttårsdag, <b>2.4</b>: Skjærtorsdag, ...". The site
publishes them a few years ahead; years it has none for are left out (the
screen then shows only Sundays in red). Run again when it has more:

    scripts/build_holidays.py [first_year]

first_year defaults to this year; years are read until one has none.
"""

import datetime
import html
import os
import re
import sys
import urllib.request

URL = "https://www.norskkalender.no/default.asp?year={}"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "components", "holidays_data.h")
ENTRY = re.compile(r"<b>(\d{1,2})\.(\d{1,2})</b>:\s*([^,<]+)")


def year_holidays(year):
    req = urllib.request.Request(URL.format(year), headers={"User-Agent": "MultiDisplay build_holidays.py"})
    with urllib.request.urlopen(req, timeout=30) as r:
        page = r.read().decode("latin-1")
    days = {}
    for block in re.findall(r"<div class='holidaytext'>(.*?)</div>", page, re.S):
        for d, m, name in ENTRY.findall(block):
            date = datetime.date(year, int(m), int(d))  # raises on nonsense
            name = html.unescape(name).strip()
            days[date] = f"{days[date]} / {name}" if date in days else name
    return days


def main():
    first = int(sys.argv[1]) if len(sys.argv) > 1 else datetime.date.today().year
    rows = []
    year = first
    while True:
        days = year_holidays(year)
        if not days:
            break
        rows += sorted(days.items())
        print(f"{year}: {len(days)} holidays")
        year += 1
    if not rows:
        sys.exit("no holidays found - has norskkalender.no changed?")
    last = year - 1
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/build_holidays.py from norskkalender.no - do not edit.\n"
                f" * Norwegian public holidays {first}-{last}. */\n\n"
                f"#define HOLIDAYS_FIRST_YEAR {first}\n#define HOLIDAYS_LAST_YEAR {last}\n\n"
                "static const holiday_t HOLIDAYS[] = {\n")
        for date, name in rows:
            # Non-ASCII as \x escapes, each closing its string so a following
            # hex digit isn't read as part of it.
            lit = ""
            for ch in name:
                if ord(ch) < 0x80 and ch not in '"\\':
                    lit += ch
                else:
                    lit += "".join(f"\\x{b:02X}" for b in ch.encode("utf-8")) + '" "'
            lit = f'"{lit}"'.replace(' ""', "")
            f.write(f"    {{ {date.year}, {date.month}, {date.day}, {lit} }},\n")
        f.write("};\n")
    print(f"wrote {len(rows)} days to {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
